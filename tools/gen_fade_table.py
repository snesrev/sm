#!/usr/bin/env python3
# Writes the GBA build's table of fade steps (src/sm_82.c's FadeStep):
# for each fade length the game uses (palette_change_denom), each step
# |a| from 1 to the length, and each channel value |k| and target |j| (0-31),
# what CalculateNthTransitionColorComponentFromXtoY works out, as it does
# (16-bit arithmetic, the SNES's divider).
#
#     gen_fade_table.py OUT.c
import sys

DENOMS = (6, 8, 12, 15)


def component(a, k, j, denom):
    if a == 0:
        return k
    v4 = a - 1
    if v4 == denom:
        return j
    diff = (j - k) & 0xffff
    dividend = ((-diff & 0xffff) if diff & 0x8000 else diff) << 8 & 0xffff
    divisor = (denom - (v4 + 1) + 1) & 0xff
    q = 0xffff if divisor == 0 else dividend // divisor
    r18 = (-q & 0xffff) if diff & 0x8000 else q
    return ((r18 + (k << 8)) & 0xffff) >> 8


out = ['// Generated by tools/gen_fade_table.py: see src/sm_82.c\'s FadeStep.',
       '#include <stdint.h>', '']
for denom in DENOMS:
    out.append('const uint8_t kFadeSteps%d[%d][1024] = {' % (denom, denom))
    for a in range(1, denom + 1):
        vals = [component(a, k, j, denom) for k in range(32) for j in range(32)]
        out.append('  {' + ','.join(map(str, vals)) + '},')
    out.append('};')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
